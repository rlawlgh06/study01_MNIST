/**
 * desktop_version/model.py 의 숫자인식CNN 순전파를 순수 자바스크립트로 옮긴 것입니다.
 * 층 순서와 메모리 배치를 PyTorch 와 똑같이 맞춰야 같은 값이 나옵니다.
 *
 * 드롭아웃은 추론에서 쓰지 않으므로 건너뜁니다(데스크톱도 모델.eval() 로 끕니다).
 *
 * 메모리 배치 약속:
 *   합성곱 가중치 [출력채널, 입력채널, 3, 3] 행 우선
 *   특징맵        [채널, y, x]              행 우선
 *   완전연결 가중치 [출력, 입력]              행 우선
 */

const 창크기 = 3;

/**
 * 패딩 없는 3×3 합성곱입니다. 출력 크기는 입력보다 2 작아집니다.
 * 누적은 자바스크립트 수(배정밀도)로 하고 저장할 때만 float32 로 떨어집니다.
 */
function 합성곱(입력, 입채널, 입세로, 입가로, 가중치, 편향, 출채널) {
  const 출세로 = 입세로 - (창크기 - 1);
  const 출가로 = 입가로 - (창크기 - 1);
  const 출력 = new Float32Array(출채널 * 출세로 * 출가로);
  const 채널면적 = 입세로 * 입가로;

  for (let 출 = 0; 출 < 출채널; 출++) {
    const 출기준 = 출 * 출세로 * 출가로;
    for (let y = 0; y < 출세로; y++) {
      for (let x = 0; x < 출가로; x++) {
        let 합 = 편향[출];
        for (let 입 = 0; 입 < 입채널; 입++) {
          const 가중치기준 = (출 * 입채널 + 입) * 창크기 * 창크기;
          const 입력기준 = 입 * 채널면적;
          for (let ky = 0; ky < 창크기; ky++) {
            const 입줄 = 입력기준 + (y + ky) * 입가로 + x;
            const 가줄 = 가중치기준 + ky * 창크기;
            합 += 입력[입줄] * 가중치[가줄]
                + 입력[입줄 + 1] * 가중치[가줄 + 1]
                + 입력[입줄 + 2] * 가중치[가줄 + 2];
          }
        }
        출력[출기준 + y * 출가로 + x] = 합;
      }
    }
  }
  return 출력;
}

/** 자리를 바꾸지 않고 음수를 0 으로 만듭니다. */
function 렐루(값들) {
  for (let i = 0; i < 값들.length; i++) {
    if (값들[i] < 0) 값들[i] = 0;
  }
  return 값들;
}

/** 2×2 최대 풀링, 보폭 2. 크기가 절반이 됩니다. */
function 맥스풀링2(입력, 채널, 입세로, 입가로) {
  const 출세로 = 입세로 >> 1;
  const 출가로 = 입가로 >> 1;
  const 출력 = new Float32Array(채널 * 출세로 * 출가로);
  for (let c = 0; c < 채널; c++) {
    const 입기준 = c * 입세로 * 입가로;
    const 출기준 = c * 출세로 * 출가로;
    for (let y = 0; y < 출세로; y++) {
      const 위줄 = 입기준 + (2 * y) * 입가로;
      const 아래줄 = 위줄 + 입가로;
      for (let x = 0; x < 출가로; x++) {
        const 왼 = 2 * x;
        const 최대 = Math.max(입력[위줄 + 왼], 입력[위줄 + 왼 + 1],
                              입력[아래줄 + 왼], 입력[아래줄 + 왼 + 1]);
        출력[출기준 + y * 출가로 + x] = 최대;
      }
    }
  }
  return 출력;
}

/** 완전연결 층. 가중치는 [출력수, 입력수] 행 우선입니다. */
function 완전연결(입력, 가중치, 편향, 출력수, 입력수) {
  const 출력 = new Float32Array(출력수);
  for (let j = 0; j < 출력수; j++) {
    const 시작 = j * 입력수;
    let 합 = 편향[j];
    for (let i = 0; i < 입력수; i++) 합 += 가중치[시작 + i] * 입력[i];
    출력[j] = 합;
  }
  return 출력;
}

/**
 * 정규화된 28×28 배열(길이 784)을 받아 0~9 로짓 10개를 돌려줍니다.
 * model.py 의 forward 와 같은 순서입니다.
 */
export function 순전파(정규화배열, 텐서) {
  // 28×28 → 32채널 26×26
  let 특징 = 합성곱(정규화배열, 1, 28, 28,
                    텐서['합성곱1.weight'], 텐서['합성곱1.bias'], 32);
  렐루(특징);

  // 32채널 26×26 → 64채널 24×24
  특징 = 합성곱(특징, 32, 26, 26,
                텐서['합성곱2.weight'], 텐서['합성곱2.bias'], 64);
  렐루(특징);

  // 64채널 24×24 → 64채널 12×12 (= 9216)
  // 이 배열의 색인 순서가 곧 PyTorch flatten(1) 의 순서입니다: c*144 + y*12 + x
  특징 = 맥스풀링2(특징, 64, 24, 24);

  const 은닉 = 완전연결(특징, 텐서['완전연결1.weight'], 텐서['완전연결1.bias'], 128, 9216);
  렐루(은닉);

  return 완전연결(은닉, 텐서['완전연결2.weight'], 텐서['완전연결2.bias'], 10, 128);
}

/** 로짓을 확률로 바꿉니다. 최대값을 빼서 지수가 넘치지 않게 합니다. */
export function 소프트맥스(로짓) {
  let 최대 = -Infinity;
  for (let i = 0; i < 로짓.length; i++) {
    if (로짓[i] > 최대) 최대 = 로짓[i];
  }
  const 확률 = new Float32Array(로짓.length);
  let 합 = 0;
  for (let i = 0; i < 로짓.length; i++) {
    const 값 = Math.exp(로짓[i] - 최대);
    확률[i] = 값;
    합 += 값;
  }
  for (let i = 0; i < 확률.length; i++) 확률[i] /= 합;
  return 확률;
}

/** 순전파 + 소프트맥스 + argmax 를 한 번에 합니다. */
export function 예측(정규화배열, 텐서) {
  const 로짓 = 순전파(정규화배열, 텐서);
  const 확률 = 소프트맥스(로짓);
  let 숫자 = 0;
  for (let i = 1; i < 확률.length; i++) {
    if (확률[i] > 확률[숫자]) 숫자 = i;
  }
  return { 숫자, 확률, 로짓 };
}
