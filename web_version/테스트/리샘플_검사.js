/**
 * 란초스_축소 가 PIL 의 Image.resize(..., LANCZOS) 와 같은 바이트를 내는지 대조합니다.
 * 기대값은 tools/고정표본_만들기.py 가 PIL 로 직접 만든 것입니다.
 */
import { 검사_모음, 바이트배열_같음_확인, base64_바이트 } from './검사틀.js';
import { 란초스_축소 } from '../js/리샘플.js';

export function 만들기(고정표본) {
  const 모음 = 검사_모음('리샘플 (PIL LANCZOS 대조)');

  for (const 표본 of 고정표본.리샘플) {
    const 설명 = `${표본.이름}: ${표본.입가로}×${표본.입세로} → ${표본.새가로}×${표본.새세로}`;
    모음.검사(설명, () => {
      const 실제 = 란초스_축소(
        base64_바이트(표본.입력), 표본.입가로, 표본.입세로, 표본.새가로, 표본.새세로);
      바이트배열_같음_확인(실제, base64_바이트(표본.기대), 표본.이름);
    });
  }

  모음.검사('크기가 같으면 원본을 그대로 돌려준다', () => {
    const 입력 = new Uint8Array([0, 40, 200, 255]);
    바이트배열_같음_확인(란초스_축소(입력, 2, 2, 2, 2), 입력, '항등');
  });

  return 모음;
}
