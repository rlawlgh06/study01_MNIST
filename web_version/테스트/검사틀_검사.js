/**
 * 검사틀 자신이 제대로 동작하는지 확인합니다.
 * 통과를 통과로, 실패를 실패로 보고하지 못하면 뒤의 모든 검사 결과를 믿을 수 없습니다.
 */
import {
  검사_모음, 같음_확인, 바이트배열_같음_확인, 실수배열_근사_확인,
  base64_바이트, base64_실수,
} from './검사틀.js';

export function 만들기() {
  const 모음 = 검사_모음('검사틀 자기검사');

  모음.검사('통과하는 검사는 통과로 보고된다', async () => {
    const 속모음 = 검사_모음('속');
    속모음.검사('참', () => 같음_확인(1, 1, '하나'));
    const { 결과 } = await 속모음.실행();
    같음_확인(결과.length, 1, '결과 개수');
    같음_확인(결과[0].통과, true, '통과 여부');
  });

  모음.검사('실패하는 검사는 실패로 보고되고 메시지가 남는다', async () => {
    const 속모음 = 검사_모음('속');
    속모음.검사('거짓', () => 같음_확인(1, 2, '하나'));
    const { 결과 } = await 속모음.실행();
    같음_확인(결과[0].통과, false, '통과 여부');
    같음_확인(결과[0].메시지.includes('하나'), true, '메시지에 설명 포함');
  });

  모음.검사('바이트배열 비교는 처음 어긋난 색인을 알려 준다', async () => {
    const 속모음 = 검사_모음('속');
    속모음.검사('어긋남', () => 바이트배열_같음_확인(
      new Uint8Array([1, 2, 9]), new Uint8Array([1, 2, 3]), '표본'));
    const { 결과 } = await 속모음.실행();
    같음_확인(결과[0].통과, false, '통과 여부');
    같음_확인(결과[0].메시지.includes('색인 2'), true, '색인 표시');
  });

  모음.검사('실수배열 근사 비교는 허용오차 안이면 통과한다', () => {
    const 최대오차 = 실수배열_근사_확인(
      new Float32Array([1.0, 2.0]), [1.0004, 2.0], 1e-3, '표본');
    같음_확인(최대오차 < 1e-3, true, '최대오차');
  });

  모음.검사('base64 디코더가 바이트와 실수를 되살린다', () => {
    // [1, 2, 255] 를 base64 로 적은 것
    바이트배열_같음_확인(base64_바이트('AQL/'), new Uint8Array([1, 2, 255]), '바이트');
    // float32 1.0, -2.5 리틀엔디언
    const 실수 = base64_실수('AACAPwAAIMA=');
    같음_확인(실수.length, 2, '실수 개수');
    같음_확인(실수[0], 1, '첫 값');
    같음_확인(실수[1], -2.5, '둘째 값');
  });

  return 모음;
}
