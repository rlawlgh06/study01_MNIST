/**
 * MNIST_형식으로_변환 이 데스크톱의 같은 이름 함수와 같은 28×28 을 내는지 대조합니다.
 * 기대값은 tools/고정표본_만들기.py 가 desktop_version/draw_predict.py 를
 * 직접 호출해서 만든 것입니다.
 */
import { 검사_모음, 같음_확인, 바이트배열_같음_확인, base64_바이트 } from './검사틀.js';
import { MNIST_형식으로_변환, 파이썬_반올림 } from '../js/전처리.js';

export function 만들기(고정표본) {
  const 모음 = 검사_모음('전처리 (데스크톱 파이프라인 대조)');

  모음.검사('파이썬_반올림 은 은행가 반올림이다 (0.5 는 짝수 쪽으로)', () => {
    같음_확인(파이썬_반올림(12.5), 12, 'round(12.5)');
    같음_확인(파이썬_반올림(13.5), 14, 'round(13.5)');
    같음_확인(파이썬_반올림(0.5), 0, 'round(0.5)');
    같음_확인(파이썬_반올림(1.5), 2, 'round(1.5)');
    같음_확인(파이썬_반올림(2.4), 2, 'round(2.4)');
    같음_확인(파이썬_반올림(2.6), 3, 'round(2.6)');
    같음_확인(파이썬_반올림(-2.5), -2, 'round(-2.5)');
    같음_확인(파이썬_반올림(-3.5), -4, 'round(-3.5)');
  });

  for (const 표본 of 고정표본.전처리) {
    if (표본.기대없음) {
      모음.검사(`${표본.이름}: 아무것도 그리지 않으면 null`, () => {
        const 결과 = MNIST_형식으로_변환(base64_바이트(표본.입력), 표본.가로, 표본.세로);
        같음_확인(결과, null, 표본.이름);
      });
      continue;
    }

    const 중간 = 표본.중간;
    const 설명 = `${표본.이름}: ${중간.잘가로}×${중간.잘세로} → `
      + `${중간.새가로}×${중간.새세로}, 이동(${중간.이동x}, ${중간.이동y})`;

    모음.검사(설명, () => {
      const 결과 = MNIST_형식으로_변환(base64_바이트(표본.입력), 표본.가로, 표본.세로);
      같음_확인(결과 === null, false, `${표본.이름}: null 이 아니어야 함`);
      바이트배열_같음_확인(결과.미리보기, base64_바이트(표본.기대28), 표본.이름);
      같음_확인(결과.정규화배열.length, 784, '정규화배열 길이');
    });
  }

  모음.검사('정규화는 (값/255 - 0.1307) / 0.3081 이다', () => {
    // 가운데 한 화소만 검게 찍은 3×3 그림. 흰 배경이므로 255 로 채웁니다.
    const 회색조 = new Uint8Array(9).fill(255);
    회색조[4] = 0;
    const 결과 = MNIST_형식으로_변환(회색조, 3, 3);
    같음_확인(결과 === null, false, 'null 이 아니어야 함');
    // 미리보기 값 v 는 정규화배열에서 (v/255 - 평균) / 표준편차 여야 합니다.
    let 최대오차 = 0;
    for (let i = 0; i < 784; i++) {
      const 기대 = (결과.미리보기[i] / 255 - 0.1307) / 0.3081;
      최대오차 = Math.max(최대오차, Math.abs(결과.정규화배열[i] - 기대));
    }
    같음_확인(최대오차 < 1e-5, true, `정규화 최대오차 ${최대오차}`);
  });

  return 모음;
}
