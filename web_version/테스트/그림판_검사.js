/**
 * 그림판이 모델에 넘길 회색조 배열을 제대로 만드는지 확인합니다.
 * 특히 '지우면 흰 배경'이 되는지 — 캔버스 기본값은 투명이고 투명 화소의 RGB 는 0 이라
 * 흰색으로 채우지 않으면 배경이 검게 읽혀 전처리가 통째로 뒤집힙니다.
 */
import { 검사_모음, 같음_확인 } from './검사틀.js';
import { 그림판_만들기, 칠판크기 } from '../js/그림판.js';
import { MNIST_형식으로_변환 } from '../js/전처리.js';

function 새_그림판() {
  const 화면 = document.createElement('canvas');
  const 모델 = document.createElement('canvas');
  const 그림판 = 그림판_만들기(화면, 모델, { 그리기끝나면: () => {} });
  그림판.지우기();
  return 그림판;
}

export function 만들기() {
  const 모음 = 검사_모음('그림판');

  모음.검사('회색조 배열의 길이는 280 × 280 이다', () => {
    같음_확인(새_그림판().회색조_가져오기().length, 칠판크기 * 칠판크기, '길이');
  });

  모음.검사('지운 직후에는 모든 화소가 흰색(255)이다', () => {
    const 회색조 = 새_그림판().회색조_가져오기();
    let 흰색아닌개수 = 0;
    let 첫자리 = -1;
    for (let i = 0; i < 회색조.length; i++) {
      if (회색조[i] !== 255) {
        흰색아닌개수 += 1;
        if (첫자리 < 0) 첫자리 = i;
      }
    }
    같음_확인(흰색아닌개수, 0,
      `흰색이 아닌 화소 ${흰색아닌개수}개 (첫 자리 ${첫자리}). ` +
      '모델용 캔버스를 흰색으로 채웠는지 확인하세요');
  });

  모음.검사('지운 직후에는 비어 있고 전처리가 null 을 준다', () => {
    const 그림판 = 새_그림판();
    같음_확인(그림판.비었나(), true, '비었나');
    같음_확인(MNIST_형식으로_변환(그림판.회색조_가져오기(), 칠판크기, 칠판크기), null, '전처리');
  });

  모음.검사('선을 그으면 그 자리가 검어지고 모서리는 흰색으로 남는다', () => {
    const 그림판 = 새_그림판();
    그림판.선_그리기([[40, 140], [240, 140]]);
    const 회색조 = 그림판.회색조_가져오기();
    같음_확인(회색조[140 * 칠판크기 + 140], 0, '선 한가운데는 검정');
    같음_확인(회색조[0], 255, '왼쪽 위 모서리는 흰색');
    같음_확인(회색조[회색조.length - 1], 255, '오른쪽 아래 모서리는 흰색');
    같음_확인(그림판.비었나(), false, '비어 있지 않음');
  });

  모음.검사('점 하나만 찍어도 자국이 남는다', () => {
    const 그림판 = 새_그림판();
    그림판.선_그리기([[140, 140]]);
    같음_확인(그림판.회색조_가져오기()[140 * 칠판크기 + 140], 0, '가운데가 검정');
  });

  모음.검사('지우면 다시 빈 상태로 돌아간다', () => {
    const 그림판 = 새_그림판();
    그림판.선_그리기([[40, 140], [240, 140]]);
    그림판.지우기();
    같음_확인(그림판.비었나(), true, '비었나');
  });

  return 모음;
}
