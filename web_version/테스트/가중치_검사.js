/**
 * 가중치 로더가 실제 파일을 제대로 읽고, 망가진 입력에는 조용히 NaN 을 내는 대신
 * 원인을 알려 주는지 확인합니다.
 */
import { 검사_모음, 같음_확인 } from './검사틀.js';
import { 가중치_불러오기, 기대하는_모양 } from '../js/가중치.js';

export function 만들기(텐서) {
  const 모음 = 검사_모음('가중치');

  모음.검사('실제 가중치 파일을 읽어 8개 텐서를 만든다', () => {
    같음_확인(텐서 === null, false, '텐서가 실려 있어야 함');
    같음_확인(Object.keys(텐서).length, 8, '텐서 개수');
  });

  for (const [이름, 모양] of Object.entries(기대하는_모양)) {
    const 개수 = 모양.reduce((곱, 길이) => 곱 * 길이, 1);
    모음.검사(`${이름} 의 값 개수가 ${개수.toLocaleString()} 개다`, () => {
      같음_확인(텐서[이름] instanceof Float32Array, true, `${이름} 자료형`);
      같음_확인(텐서[이름].length, 개수, `${이름} 개수`);
    });
  }

  모음.검사('값이 전부 0 이거나 NaN 이 아니다', () => {
    const 값 = 텐서['합성곱1.weight'];
    let 영아닌개수 = 0;
    for (let i = 0; i < 값.length; i++) {
      같음_확인(Number.isFinite(값[i]), true, `색인 ${i} 가 유한수`);
      if (값[i] !== 0) 영아닌개수 += 1;
    }
    같음_확인(영아닌개수 > 값.length / 2, true, `0 이 아닌 값 ${영아닌개수}/${값.length}`);
  });

  모음.검사('없는 경로를 주면 복구 안내가 담긴 가중치오류를 던진다', async () => {
    let 잡힌오류 = null;
    try {
      await 가중치_불러오기('없는폴더/');
    } catch (오류) {
      잡힌오류 = 오류;
    }
    같음_확인(잡힌오류 === null, false, '오류가 나야 함');
    같음_확인(잡힌오류.name, '가중치오류', '오류 종류');
    같음_확인(typeof 잡힌오류.안내 === 'string' && 잡힌오류.안내.length > 0, true, '안내 문구');
  });

  return 모음;
}
